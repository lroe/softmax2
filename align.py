# Regenerates preview/js/data/timeline.js from the known narration script and the
# forced-aligned word timings in words.json.
#
# words.json is the faster-whisper output after alignment to script.txt: its word
# sequence is identical to the script (3625 words) and carries start/end times.

import json, re

script = [l.strip() for l in open('script.txt', encoding='utf-8').read().splitlines() if l.strip()]
raw = json.load(open('words.json', encoding='utf-8'))
words = raw['words']
duration = raw['duration']

flat = []
for line_no, text in enumerate(script, 1):
    for token in text.split():
        flat.append((line_no, token))

assert len(flat) == len(words), f'script has {len(flat)} words, timings have {len(words)}'

lines = []
for line_no, text in enumerate(script, 1):
    toks = []
    for (ln, token), timing in zip(flat, words):
        if ln != line_no:
            continue
        toks.append({'w': token, 's': round(timing['start'], 3), 'e': round(timing['end'], 3)})
    lines.append({
        'n': line_no,
        'text': text,
        'start': toks[0]['s'],
        'end': toks[-1]['e'],
        'words': toks,
    })

def jsstr(s):
    return json.dumps(s, ensure_ascii=False)

with open('preview/js/data/timeline.js', 'w', encoding='utf-8') as f:
    f.write('// Generated by align.py from script.txt + words.json (faster-whisper forced alignment).\n')
    f.write('// Word timings are absolute seconds; there is no drift correction at runtime.\n\n')
    f.write('export const LINES = [\n')
    for ln in lines:
        ws = ', '.join('{w:%s,s:%.3f,e:%.3f}' % (jsstr(w['w']), w['s'], w['e']) for w in ln['words'])
        f.write('  {n:%d,text:%s,start:%.3f,end:%.3f,words:[%s]},\n' % (
            ln['n'], jsstr(ln['text']), ln['start'], ln['end'], ws))
    f.write('];\n\n')
    f.write('export const WORD_ROWS = LINES.flatMap(l => l.words.map(w => ({...w, line:l.n})));\n\n')
    f.write('export const DURATION = %s;\n\n' % round(duration, 3))
    f.write('''const byLine = new Map(LINES.map(l => [l.n, l]));

export function line(n) { return byLine.get(n); }
export function start(n) { const l = byLine.get(n); return l ? l.start : 0; }
export function end(n) { const l = byLine.get(n); return l ? l.end : 0; }
export function lineText(n) { const l = byLine.get(n); return l ? l.text : ''; }

// Flatten each word into searchable keys. Punctuation and hyphens become spaces
// so "exp-m-one" matches queries written as "exp m one".
const KEYS = [];
for (let i = 0; i < WORD_ROWS.length; i++) {
  const parts = WORD_ROWS[i].w.toLowerCase()
    .replace(/[^a-z0-9']+/g, ' ')
    .trim().split(/\\s+/).filter(Boolean);
  for (const k of parts) KEYS.push({ k, i });
}

function queryKeys(phrase) {
  return phrase.toLowerCase().replace(/[^a-z0-9']+/g, ' ').trim().split(/\\s+/).filter(Boolean);
}

function findPhrase(phrase, fromLine = 0, occurrence = 1) {
  const q = queryKeys(phrase);
  if (!q.length) return null;
  let found = 0;
  for (let i = 0; i < KEYS.length; i++) {
    if (WORD_ROWS[KEYS[i].i].line < fromLine) continue;
    let ok = true;
    for (let j = 0; j < q.length; j++) {
      if (!KEYS[i + j] || KEYS[i + j].k !== q[j]) { ok = false; break; }
    }
    if (ok) {
      found++;
      if (found === occurrence) return { a: KEYS[i].i, b: KEYS[i + q.length - 1].i };
    }
  }
  return null;
}

// Find a phrase in the aligned script. Returns the start time of its first word.
export function at(phrase, fromLine = 0, occurrence = 1) {
  const r = findPhrase(phrase, fromLine, occurrence);
  return r ? WORD_ROWS[r.a].s : 0;
}

export function atEnd(phrase, fromLine = 0, occurrence = 1) {
  const r = findPhrase(phrase, fromLine, occurrence);
  return r ? WORD_ROWS[r.b].e : 0;
}

// Find the nth word of a line (1-based), useful for long paragraphs.
export function wordAt(n, index = 1) {
  const l = byLine.get(n);
  if (!l) return 0;
  const w = l.words[Math.max(0, Math.min(l.words.length - 1, index - 1))];
  return w ? w.s : l.start;
}
''')

print('wrote preview/js/data/timeline.js')
print(f'{len(lines)} lines · {len(words)} words · {duration:.2f}s')
for ln in lines:
    print(f"{ln['n']:3d}  {ln['start']:7.2f}  {ln['end']:7.2f}  {ln['text'][:64]}")
